-- IPv4 Academy V2 foundation
-- Safe to apply alongside V1 because all objects use the academy_v2 schema.

create schema if not exists academy_v2;

create table if not exists academy_v2.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text not null,
  role text not null default 'student' check (role in ('student','trainer','admin')),
  group_no text,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists academy_v2.courses (
  id bigint generated by default as identity primary key,
  code text unique not null,
  title text not null,
  description text,
  status text not null default 'draft' check (status in ('draft','published','archived')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists academy_v2.lessons (
  id bigint generated by default as identity primary key,
  course_id bigint not null references academy_v2.courses(id) on delete cascade,
  title text not null,
  slug text unique not null,
  sort_order int not null default 0,
  content jsonb not null default '{}'::jsonb,
  is_published boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists academy_v2.questions (
  id bigint generated by default as identity primary key,
  course_id bigint references academy_v2.courses(id) on delete set null,
  lesson_id bigint references academy_v2.lessons(id) on delete set null,
  question_type text not null default 'mcq' check (question_type in ('mcq','true_false','short_answer','matching')),
  prompt text not null,
  options jsonb not null default '[]'::jsonb,
  answer jsonb not null default '{}'::jsonb,
  difficulty text not null default 'easy' check (difficulty in ('easy','medium','hard')),
  topic text,
  points numeric(8,2) not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists academy_v2.exams (
  id bigint generated by default as identity primary key,
  course_id bigint references academy_v2.courses(id) on delete set null,
  title text not null,
  instructions text,
  duration_minutes int not null default 20,
  pass_score numeric(5,2) not null default 60,
  attempts_limit int not null default 1,
  status text not null default 'draft' check (status in ('draft','scheduled','open','closed','archived')),
  starts_at timestamptz,
  ends_at timestamptz,
  created_by uuid references academy_v2.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists academy_v2.exam_questions (
  exam_id bigint not null references academy_v2.exams(id) on delete cascade,
  question_id bigint not null references academy_v2.questions(id) on delete cascade,
  sort_order int not null default 0,
  points numeric(8,2) not null default 1,
  primary key (exam_id,question_id)
);

create table if not exists academy_v2.attempts (
  id bigint generated by default as identity primary key,
  exam_id bigint not null references academy_v2.exams(id) on delete cascade,
  student_id uuid not null references academy_v2.profiles(id) on delete cascade,
  status text not null default 'in_progress' check (status in ('in_progress','submitted','graded','expired')),
  started_at timestamptz not null default now(),
  submitted_at timestamptz,
  score numeric(6,2),
  passed boolean,
  duration_seconds int
);

create table if not exists academy_v2.attempt_answers (
  id bigint generated by default as identity primary key,
  attempt_id bigint not null references academy_v2.attempts(id) on delete cascade,
  question_id bigint not null references academy_v2.questions(id) on delete cascade,
  answer jsonb not null default '{}'::jsonb,
  is_correct boolean,
  points_awarded numeric(8,2) not null default 0,
  answered_at timestamptz not null default now(),
  unique(attempt_id,question_id)
);

create table if not exists academy_v2.practice_attempts (
  id bigint generated by default as identity primary key,
  student_id uuid not null references academy_v2.profiles(id) on delete cascade,
  lesson_id bigint references academy_v2.lessons(id) on delete set null,
  topic text,
  question_id bigint references academy_v2.questions(id) on delete set null,
  answer jsonb not null default '{}'::jsonb,
  is_correct boolean,
  duration_seconds int,
  created_at timestamptz not null default now()
);

create table if not exists academy_v2.student_progress (
  student_id uuid not null references academy_v2.profiles(id) on delete cascade,
  course_id bigint not null references academy_v2.courses(id) on delete cascade,
  progress_pct numeric(5,2) not null default 0,
  mastery_pct numeric(5,2) not null default 0,
  streak_days int not null default 0,
  last_activity_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key(student_id,course_id)
);

create table if not exists academy_v2.notifications (
  id bigint generated by default as identity primary key,
  user_id uuid not null references academy_v2.profiles(id) on delete cascade,
  event_key text not null,
  title text not null,
  body text,
  read_at timestamptz,
  created_at timestamptz not null default now(),
  unique(user_id,event_key)
);

create table if not exists academy_v2.achievements (
  id bigint generated by default as identity primary key,
  code text unique not null,
  title text not null,
  description text,
  icon text,
  rule jsonb not null default '{}'::jsonb
);

create table if not exists academy_v2.student_achievements (
  student_id uuid not null references academy_v2.profiles(id) on delete cascade,
  achievement_id bigint not null references academy_v2.achievements(id) on delete cascade,
  earned_at timestamptz not null default now(),
  primary key(student_id,achievement_id)
);

create index if not exists idx_v2_attempts_student on academy_v2.attempts(student_id,started_at desc);
create index if not exists idx_v2_practice_student on academy_v2.practice_attempts(student_id,created_at desc);
create index if not exists idx_v2_questions_topic on academy_v2.questions(topic,is_active);
create index if not exists idx_v2_notifications_user on academy_v2.notifications(user_id,created_at desc);

