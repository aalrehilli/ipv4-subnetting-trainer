-- Base helper. Trainer/admin checks are enforced in SQL, not trusted in the UI.
create or replace function academy_v2.is_staff()
returns boolean
language sql
stable
as $$
  select exists(
    select 1 from academy_v2.profiles p
    where p.id = auth.uid() and p.role in ('trainer','admin') and p.is_active
  );
$$;

create policy v2_profiles_self on academy_v2.profiles for select using (id=auth.uid() or academy_v2.is_staff());
create policy v2_courses_read on academy_v2.courses for select using (status='published' or academy_v2.is_staff());
create policy v2_lessons_read on academy_v2.lessons for select using (
  is_published or academy_v2.is_staff()
);
create policy v2_questions_read on academy_v2.questions for select using (is_active or academy_v2.is_staff());
create policy v2_exams_read on academy_v2.exams for select using (academy_v2.is_staff() or status in ('scheduled','open'));
create policy v2_exam_questions_read on academy_v2.exam_questions for select using (
  exists(select 1 from academy_v2.exams e where e.id=exam_id and (e.status in ('scheduled','open') or academy_v2.is_staff()))
);
create policy v2_attempts_self on academy_v2.attempts for select using (student_id=auth.uid() or academy_v2.is_staff());
create policy v2_attempt_answers_self on academy_v2.attempt_answers for select using (
  exists(select 1 from academy_v2.attempts a where a.id=attempt_id and (a.student_id=auth.uid() or academy_v2.is_staff()))
);
create policy v2_practice_self on academy_v2.practice_attempts for select using (student_id=auth.uid() or academy_v2.is_staff());
create policy v2_progress_self on academy_v2.student_progress for select using (student_id=auth.uid() or academy_v2.is_staff());
create policy v2_notifications_self on academy_v2.notifications for select using (user_id=auth.uid());
create policy v2_achievements_read on academy_v2.achievements for select using (true);
create policy v2_student_achievements_self on academy_v2.student_achievements for select using (student_id=auth.uid() or academy_v2.is_staff());

-- Dashboard summaries: first V2 analytics layer.
create or replace view academy_v2.student_dashboard_summary as
select
  p.id as student_id,
  p.full_name,
  p.group_no,
  coalesce(round(avg(a.score)::numeric,2),0) as avg_exam_score,
  count(a.id)::int as exam_attempts,
  coalesce(round(avg(case when pa.is_correct then 100 else 0 end)::numeric,2),0) as practice_accuracy,
  count(pa.id)::int as practice_attempts
from academy_v2.profiles p
left join academy_v2.attempts a on a.student_id=p.id and a.status in ('graded','submitted')
left join academy_v2.practice_attempts pa on pa.student_id=p.id
group by p.id,p.full_name,p.group_no;

create or replace view academy_v2.trainer_group_summary as
select
  coalesce(nullif(p.group_no,''),'غير محدد') as group_no,
  count(*)::int as students,
  count(*) filter(where p.is_active)::int as active_students
from academy_v2.profiles p
where p.role='student'
group by 1;

create or replace view academy_v2.trainer_topic_summary as
select
  coalesce(pa.topic,'غير محدد') as topic,
  count(*)::int as attempts,
  round(avg(case when pa.is_correct then 100 else 0 end)::numeric,2) as accuracy
from academy_v2.practice_attempts pa
group by 1;


-- Create a V2 profile automatically for every new Auth user.
-- Role is intentionally always student here; trainer/admin elevation is administrative only.
create or replace function academy_v2.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = academy_v2, public
as $$
begin
  insert into academy_v2.profiles(id,full_name,role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name', split_part(coalesce(new.email,'متدرب'), '@', 1), 'متدرب'),
    'student'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_v2 on auth.users;
create trigger on_auth_user_created_v2
after insert on auth.users
for each row execute procedure academy_v2.handle_new_user();

grant usage on schema academy_v2 to anon, authenticated;
grant select on academy_v2.courses,
              academy_v2.lessons,
              academy_v2.questions,
              academy_v2.exams,
              academy_v2.exam_questions,
              academy_v2.achievements to anon, authenticated;

grant select on academy_v2.profiles,
              academy_v2.attempts,
              academy_v2.attempt_answers,
              academy_v2.practice_attempts,
              academy_v2.student_progress,
              academy_v2.notifications,
              academy_v2.student_achievements to authenticated;

